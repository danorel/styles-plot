"""A figure strict mode refuses: one header word missing from the vocabulary, one cell missing from the registry.

    python examples/strict/refused.py   prints the StyleError (the README shows it, generated by docs/readme_blocks.py)

Not part of the gallery: it exists to fail.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import styles_plot as sp

EXAMPLES = Path(__file__).resolve().parent.parent


def refused(v: sp.Vocab) -> sp.Figure:
    col = sp.DotColumn("recall", "accuracy", (40, 100), (50, 75, 100),  # "recall" is not in [terms]
                       series=[sp.Series("second", {"m1": sp.Est(81, cell="acc.m1"),
                                                    "m2": sp.Est(77, cell="acc.m2")})])  # acc.m2 has no registry row
    return sp.Figure("refused", v).add(sp.DotTable(["m1", "m2"], [col]))


def error_text() -> str:
    """The StyleError strict mode raises for this figure."""
    with tempfile.TemporaryDirectory() as out:
        try:
            sp.save(refused(sp.load(EXAMPLES / "plotstyle.toml")), Path(out) / "refused.png", "post")
        except sp.StyleError as e:
            return str(e)
    raise SystemExit("examples/strict/refused.py: the figure was not refused")


if __name__ == "__main__":
    print(error_text())
    sys.exit(0)
